-- 业务管理：产品、订单与订单明细。先建产品再建订单；不插入演示数据，可重复执行。
CREATE TABLE IF NOT EXISTS biz_product (
  id BIGINT PRIMARY KEY COMMENT '产品ID',
  tenant_id BIGINT NOT NULL COMMENT '租户ID',
  sku VARCHAR(64) NOT NULL COMMENT '租户内唯一产品编码',
  name VARCHAR(120) NOT NULL COMMENT '产品名称',
  category VARCHAR(60) NOT NULL DEFAULT '' COMMENT '产品分类',
  price DECIMAL(12,2) NOT NULL COMMENT '单价，人民币元',
  stock INT NOT NULL COMMENT '可售库存，创建订单时扣减，取消时归还',
  status VARCHAR(16) NOT NULL DEFAULT '下架' COMMENT '上架/下架',
  description VARCHAR(1000) NOT NULL DEFAULT '' COMMENT '产品说明',
  version BIGINT NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  created_by BIGINT NOT NULL COMMENT '创建用户，删除用户不级联删除业务记录',
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  UNIQUE KEY uk_product_tenant_id(tenant_id,id),
  UNIQUE KEY uk_product_sku(tenant_id,sku),
  KEY ix_product_tenant_time(tenant_id,created_at,id),
  FOREIGN KEY(tenant_id) REFERENCES sys_tenant(id),
  CHECK(price>=0 AND stock>=0),
  CHECK(status IN ('上架','下架'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='产品';

CREATE TABLE IF NOT EXISTS biz_order (
  id BIGINT PRIMARY KEY COMMENT '订单ID',
  tenant_id BIGINT NOT NULL,
  order_no VARCHAR(40) NOT NULL COMMENT '服务端生成订单号',
  request_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '提交幂等编号',
  request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '原始请求摘要',
  customer VARCHAR(100) NOT NULL COMMENT '客户/收货人',
  phone VARCHAR(32) NOT NULL DEFAULT '',
  address VARCHAR(300) NOT NULL DEFAULT '',
  remark VARCHAR(500) NOT NULL DEFAULT '',
  total DECIMAL(18,2) NOT NULL COMMENT '以产品锁定时的单价计算',
  status VARCHAR(16) NOT NULL DEFAULT '待付款',
  tracking_no VARCHAR(100) NOT NULL DEFAULT '' COMMENT '物流单号',
  version BIGINT NOT NULL DEFAULT 0,
  created_by BIGINT NOT NULL,
  created_dept_id BIGINT NULL COMMENT '下单时的部门，供角色数据范围过滤',
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  paid_at DATETIME(6) NULL,
  shipped_at DATETIME(6) NULL,
  completed_at DATETIME(6) NULL,
  cancelled_at DATETIME(6) NULL,
  UNIQUE KEY uk_order_tenant_id(tenant_id,id),
  UNIQUE KEY uk_order_no(tenant_id,order_no),
  UNIQUE KEY uk_order_request(tenant_id,created_by,request_id),
  KEY ix_order_tenant_time(tenant_id,created_at,id),
  KEY ix_order_owner(tenant_id,created_by,created_at),
  FOREIGN KEY(tenant_id) REFERENCES sys_tenant(id),
  CHECK(total>=0),
  CHECK(status IN ('待付款','待发货','已发货','已完成','已取消'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='订单';

CREATE TABLE IF NOT EXISTS biz_order_item (
  id BIGINT PRIMARY KEY,
  tenant_id BIGINT NOT NULL,
  order_id BIGINT NOT NULL,
  product_id BIGINT NOT NULL,
  sku VARCHAR(64) NOT NULL COMMENT '下单时的产品编码快照',
  name VARCHAR(120) NOT NULL COMMENT '下单时的产品名称快照',
  price DECIMAL(12,2) NOT NULL COMMENT '单价快照',
  quantity INT NOT NULL,
  subtotal DECIMAL(18,2) NOT NULL,
  UNIQUE KEY uk_order_product(tenant_id,order_id,product_id),
  FOREIGN KEY(tenant_id,order_id) REFERENCES biz_order(tenant_id,id),
  FOREIGN KEY(tenant_id,product_id) REFERENCES biz_product(tenant_id,id),
  CHECK(quantity>0 AND price>=0 AND subtotal>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='订单产品与价格快照';
